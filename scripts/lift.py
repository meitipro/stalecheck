"""Regenerate lib/stalecheck_consensus.py from the contract.

    python scripts/lift.py

The lifted module claims to be the placement rules "as the contract runs
them". Maintaining it by hand makes that claim false the first time
somebody edits one side, so it is generated, and
tests/test_logic.py::TestTheLiftedLib compares the two parsed trees function by
function. scripts/mutate.py runs this inside every mutated copy, so the parity
test can never stand in for the behavioural test a mutation deserves.
"""

import ast
import pathlib

ROOT = pathlib.Path(__file__).absolute().parent.parent
CONTRACT = ROOT / "contracts" / "stalecheck.py"
OUT = ROOT / "lib" / "stalecheck_consensus.py"

CONSTANTS = [
    "FRESH", "STALE", "FUTURE", "UNDATED", "NONE", "MAX_SHOWN", "SLACK_DAYS", "MAX_REASON",
]

FUNCTIONS = [
    "today_of", "parse_day", "reading_sound", "stalecheck_agrees", "verdict_of", "window_of", "installment",
    "excerpt", "normalise_reading", "sanitise_reason", "fence", "build_prompt",
]

HEADER = '''# stalecheck_consensus.py - the freshness rules, lifted out to be copied.
#
# GENERATED by scripts/lift.py from contracts/stalecheck.py. Do not edit by
# hand: tests/test_logic.py compares the two parsed trees function by function.
#
# GenLayer contracts run as ONE Python file inside the GenVM. There is no
# cross-file import at deploy time, so this is not a module a contract imports:
# it is a curated block, for reading and lifting into another project without
# reading a whole contract first.
#
# Everything here is pure. No storage, no network, no model. `fetch()`, the
# one impure step that reads the page itself, is deliberately not lifted here.
#
# The ideas worth lifting: the model is never asked whether a page is current.
# It reads ONE fact off the page, the date the page gives as its own
# last-updated date, and only that string crosses consensus. The contract then
# compares it with its own clock: verdict_of() is arithmetic, not judgment.

'''

def main():
    src = CONTRACT.read_text(encoding="utf-8")
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)

    def segment(node, with_comments=False):
        start = node.lineno - 1
        while with_comments and start > 0 and lines[start - 1].startswith("#"):
            start -= 1
        return "".join(lines[start:node.end_lineno]).rstrip("\n")

    parts = []
    for name in CONSTANTS:
        for n in tree.body:
            if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in n.targets):
                parts.append(segment(n))
                break
        else:
            raise SystemExit(f"the contract no longer defines {name}")

    fns = []
    for name in FUNCTIONS:
        for n in tree.body:
            if isinstance(n, ast.FunctionDef) and n.name == name:
                fns.append(segment(n, with_comments=True))
                break
        else:
            raise SystemExit(f"the contract no longer defines {name}()")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(parts) + "\n\n\n" + "\n\n\n".join(fns) + "\n",
                   encoding="utf-8", newline="\n")
    print(f"  {OUT.relative_to(ROOT).as_posix()}: {len(CONSTANTS)} constants, {len(FUNCTIONS)} functions")


if __name__ == "__main__":
    main()
